let currentLang = "zh";

function t(key, ...args) {
    const dict = I18N[currentLang] || I18N.zh;
    let str = dict[key] || I18N.zh[key] || key;
    if (args && args.length > 0) {
        for (let i = 0; i < args.length; i++) {
            str = str.replace("{" + i + "}", String(args[i]));
        }
    }
    return str;
}

function setLang(lang) {
    currentLang = lang;
    localStorage.setItem("luogu_analyzer_lang", lang);
    document.documentElement.setAttribute("lang", lang === "zh" ? "zh-CN" : "en");
    applyTranslations();
}

function applyTranslations() {
    // Elements with data-i18n attribute get textContent set
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        el.textContent = t(key);
    });
    // Elements with data-i18n-placeholder get placeholder set
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        const key = el.getAttribute("data-i18n-placeholder");
        el.placeholder = t(key);
    });
    // Elements with data-i18n-title get title set
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
        const key = el.getAttribute("data-i18n-title");
        el.title = t(key);
    });
    // Elements with data-i18n-aria get aria-label set
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
        const key = el.getAttribute("data-i18n-aria");
        el.setAttribute("aria-label", t(key));
    });
    // Update page title
    document.title = t("appTitle");

    // Update save status texts (set dynamically, not via data-i18n)
    const apiKeyStatus = document.getElementById("apiKeyStatus");
    const glmApiKeyStatus = document.getElementById("glmApiKeyStatus");
    const cookieStatus = document.getElementById("cookieStatus");
    if (apiKeyStatus && apiKeyStatus.classList.contains("saved")) {
        apiKeyStatus.textContent = t("savedStatus");
    }
    if (glmApiKeyStatus && glmApiKeyStatus.classList.contains("saved")) {
        glmApiKeyStatus.textContent = t("savedStatus");
    }
    if (cookieStatus && cookieStatus.classList.contains("saved")) {
        cookieStatus.textContent = t("savedStatus");
    }

    // Refresh IDE mode toggle button text (state-aware: "在线IDE" / "退出IDE")
    if (typeof updateIdeModeBtnText === "function") {
        updateIdeModeBtnText();
    }

    // Refresh dynamically created problem-browser filter bar text
    if (typeof refreshFilterBarText === "function") {
        refreshFilterBarText();
    }

    // Refresh the search-results filter bar text (dynamically created)
    if (typeof refreshSearchResultsText === "function") {
        refreshSearchResultsText();
    }

    // Update dynamic content if a problem is loaded
    if (currentProblem) {
        renderProblem(currentProblem);
    }
    if (currentSolutions && currentSolutions.length > 0) {
        renderSolutions(currentSolutions, lastSolutionTotal);
    }
    updateSubmitPanel();
}
